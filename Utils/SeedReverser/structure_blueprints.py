def has_blueprint(key: str) -> bool:
    """该结构是否有精确蓝图数据（False 时渲染兜底示意框）。"""
    return key in BLUEPRINTS

def blueprint(key: str):
    """返回蓝图 dict 或 None（拼装结构返回 None）。"""
    return BLUEPRINTS.get(key)

def fallback_size(key: str):
    """兜底示意外框尺寸 (W, D, H) 或 None。"""
    return FALLBACK_SIZES.get(key)
